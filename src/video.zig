pub const Video = struct {
    framebuffer: [SCREEN_WIDTH * SCREEN_HEIGHT]u32 = [_]u32{0xFF000000} ** (SCREEN_WIDTH * SCREEN_HEIGHT),
    hires_mode: bool = false,
    frame_counter: u32 = 0,

    pub fn init() Video {
        return .{};
    }

    pub fn reset(self: *Video) void {
        @memset(&self.framebuffer, 0xFF000000);
        self.hires_mode = false;
        self.frame_counter = 0;
    }

    /// Render a full 50Hz frame from 48K RAM
    pub fn render_frame(self: *Video, ram: []const u8) void {
        self.frame_counter = self.frame_counter +% 1;
        const blink_phase = ((self.frame_counter / 16) & 1) != 0;

        // Detect screen mode:
        // 1. Check end-of-screen ULA attribute at $BFDF
        var initial_hires = self.hires_mode;
        const mode_byte = ram[0xBFDF] & 0x1F;
        if ((ram[0xBFDF] & 0x60) == 0) {
            if (mode_byte >= 28 and mode_byte <= 31) {
                initial_hires = true;
            } else if (mode_byte >= 24 and mode_byte <= 27) {
                initial_hires = false;
            }
        } else if (ram[0x021F] != 0 or ((ram[0x02C0] & 1) != 0)) {
            initial_hires = true;
        }

        self.hires_mode = initial_hires;
        var current_hires = initial_hires;

        var y: usize = 0;
        while (y < SCREEN_HEIGHT) : (y += 1) {
            // Lines 200..223 are always the bottom 3 rows of text in hardware
            if (y >= 200) {
                current_hires = false;
            } else if (current_hires) {
                const b0 = ram[0xA000 + (y * 40)];
                if ((b0 & 0x60) == 0 and (b0 & 0x1F) >= 24 and (b0 & 0x1F) <= 27) {
                    current_hires = false;
                }
            } else if ((y % 8) == 0) {
                const t0 = ram[0xBB80 + ((y / 8) * 40)];
                if ((t0 & 0x60) == 0 and (t0 & 0x1F) >= 28 and (t0 & 0x1F) <= 31) {
                    current_hires = true;
                }
            }

            // Start of scanline reset (SelReload): Ink is White, Paper is Black
            var ink = PALETTE[7];
            var paper = PALETTE[0];
            var double_height = false;
            var blinking = false;
            var alt_charset = false;

            const row = y / 8;
            const char_line = y % 8;

            if (current_hires) {
                // HIRES Graphic scanline (0xA000 + y * 40)
                const line_addr = 0xA000 + (y * 40);
                var col: usize = 0;
                while (col < 40) : (col += 1) {
                    const byte = ram[line_addr + col];
                    if ((byte & 0x60) == 0) {
                        // Serial Attribute
                        const attr = byte & 0x1F;
                        switch (attr) {
                            0...7 => ink = PALETTE[attr],
                            8...15 => blinking = (attr & 4) != 0,
                            16...23 => paper = PALETTE[attr & 7],
                            24...27 => current_hires = false,
                            28...31 => current_hires = true,
                            else => {},
                        }

                        const cell_color = if ((byte & 0x80) != 0) ink else paper;
                        var p: usize = 0;
                        while (p < 6) : (p += 1) {
                            self.framebuffer[y * SCREEN_WIDTH + (col * 6 + p)] = cell_color;
                        }
                    } else {
                        // Graphics pixels (6 pixels, bit 5 leftmost, bit 0 rightmost)
                        const inverse = (byte & 0x80) != 0;
                        var p: usize = 0;
                        while (p < 6) : (p += 1) {
                            const shift: u3 = @truncate(5 - p);
                            var pixel_on = (byte & (@as(u8, 1) << shift)) != 0;
                            if (inverse) {
                                pixel_on = !pixel_on;
                            }
                            if (blinking and blink_phase) {
                                pixel_on = false;
                            }
                            const color = if (pixel_on) ink else paper;
                            self.framebuffer[y * SCREEN_WIDTH + (col * 6 + p)] = color;
                        }
                    }
                }
            } else {
                // Text Mode scanline (0xBB80 + row * 40)
                const row_addr = 0xBB80 + (row * 40);
                var col: usize = 0;
                while (col < 40) : (col += 1) {
                    const ch = ram[row_addr + col];
                    if ((ch & 0x60) == 0) {
                        // Serial Attribute
                        const attr = ch & 0x1F;
                        switch (attr) {
                            0...7 => ink = PALETTE[attr],
                            8...15 => {
                                alt_charset = (attr & 1) != 0;
                                double_height = (attr & 2) != 0;
                                blinking = (attr & 4) != 0;
                            },
                            16...23 => paper = PALETTE[attr & 7],
                            24...27 => current_hires = false,
                            28...31 => {
                                if (y < 200) {
                                    current_hires = true;
                                }
                            },
                            else => {},
                        }

                        const cell_color = if ((ch & 0x80) != 0) ink else paper;
                        var p: usize = 0;
                        while (p < 6) : (p += 1) {
                            self.framebuffer[y * SCREEN_WIDTH + (col * 6 + p)] = cell_color;
                        }
                    } else {
                        const inverse = (ch & 0x80) != 0;
                        const char_code: usize = ch & 0x7F;

                        // Font base address in RAM
                        const font_base: usize = if (initial_hires or current_hires)
                            (if (alt_charset) 0x9C00 else 0x9800)
                        else
                            (if (alt_charset) 0xB800 else 0xB400);

                        const glyph_line: usize = if (double_height)
                            (if ((row & 1) != 0) 4 + (char_line / 2) else char_line / 2)
                        else
                            char_line;

                        const glyph_addr = font_base + (char_code * 8) + glyph_line;
                        var pattern: u8 = if (glyph_addr < ram.len) ram[glyph_addr] else 0;

                        // Fallback to built-in standard font if RAM font not yet populated
                        if (pattern == 0 and char_code >= 32 and char_code < 128 and !alt_charset) {
                            pattern = ORIC_FONT_STANDARD[(char_code - 32) * 8 + glyph_line];
                        }

                        var p: usize = 0;
                        while (p < 6) : (p += 1) {
                            const shift: u3 = @truncate(5 - p);
                            var pixel_on = (pattern & (@as(u8, 1) << shift)) != 0;
                            if (inverse) {
                                pixel_on = !pixel_on;
                            }
                            if (blinking and blink_phase) {
                                pixel_on = false;
                            }
                            const color = if (pixel_on) ink else paper;
                            self.framebuffer[y * SCREEN_WIDTH + (col * 6 + p)] = color;
                        }
                    }
                }
            }
        }
    }
};
